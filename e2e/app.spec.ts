test('exports every filtered row and switches between table and gallery', async ({ page }) => {
  await openDemo(page)
  await expect(page.locator('.result-summary')).toContainText('48 entries')
  await page.getByRole('button', { name: 'Sort', exact: true }).click()
  const sortDialog = page.getByRole('dialog', { name: 'Sort priorities' })
  await sortDialog.getByRole('combobox', { name: /^Priority 1/ }).selectOption('total')
  await sortDialog.getByLabel('Direction').selectOption('desc')
  await sortDialog.getByRole('button', { name: 'Done' }).click()
  if (test.info().project.name !== 'mobile') await page.getByRole('checkbox', { name: 'Select this page' }).check()
  await page.getByText('More options', { exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: /^Export/ }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toBe('black-market-collection.csv')
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(Buffer.from(chunk))
  const csv = Buffer.concat(chunks).toString('utf8')
  expect(csv.split('\r\n')).toHaveLength(49)
  const values = csv.split('\r\n').slice(1).map(line => line.match(/,"([^"]*)"\s*$/)?.[1] ?? '')
  const priced = values.filter(Boolean).map(Number)
  expect(priced).toEqual([...priced].sort((a, b) => b - a))
  expect(values.slice(-4).every(value => value === '')).toBe(true)
  await page.getByRole('button', { name: 'Gallery view' }).click()
  await expect(page.locator('.collection-grid .card-tile')).toHaveCount(8)
  await page.getByRole('button', { name: 'Next page' }).click()
  await expect(page.locator('.pagination')).toContainText('9-16 of 48')
  await page.getByRole('button', { name: 'Sort', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Sort priorities' })
  await dialog.getByLabel('Direction').first().selectOption('asc')
  await dialog.getByRole('button', { name: 'Done' }).click()
  await expect(page.locator('.pagination')).toContainText('1-8 of 48')
})

