import { expect, test } from '@playwright/test'

test('public landing rotates only the fictional showcase', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Know what you hold.' })).toBeVisible()
  const first = await page.locator('.showcase-caption h2').textContent()
  await page.reload()
  await expect(page.locator('.showcase-caption h2')).not.toHaveText(first!)
  await expect(page.locator('.hero-proof')).toContainText('Synthetic data only')
  await expect(page.locator('.landing')).not.toContainText('Valuation coverage')
})

