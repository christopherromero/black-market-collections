import { StrictMode } from 'react'
import { act, cleanup, fireEvent, renderHook, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { CollectionProvider, useCollection } from './state'
import { ImageResolution } from './ImageResolution'
import { CardArt } from './components'
import { CATALOG_KEY, printingKey, QUOTE_MAX_AGE_MS, readScryfallCard } from './scryfall'
import { COLLECTION_KEY, loadCollection, storeCollection } from './storage'
import { syntheticCsv, syntheticPricedResponse, syntheticPrinting, syntheticResponse, syntheticRow } from './test-fixtures'

const rows = (count: number) => Array.from({ length: count }, (_, i) => {
  const row = [...syntheticRow]; row[2] = `Synthetic ${String(i).padStart(3, '0')}`; row[9] = String(i)
  return row
})
const response = (number = 'PCY-1') => new Response(JSON.stringify({ ...syntheticResponse(), collector_number: number }))
const fetcher = vi.fn<typeof fetch>()
const advance = async (ms = 2000) => { await act(async () => { await vi.advanceTimersByTimeAsync(ms) }) }

function VisibleImages({ size }: { size: number }) {
  const state = useCollection()
  const visible = state.holdings.slice(state.page * size, (state.page + 1) * size)
  return <><ImageResolution rows={visible} />{visible.map(row => <CardArt key={row.id} card={row.card} />)}</>
}
function mount(size = 8) {
  return renderHook(useCollection, { wrapper: ({ children }) => <StrictMode><CollectionProvider>{children}<VisibleImages size={size} /></CollectionProvider></StrictMode> })
}
beforeEach(() => {
  localStorage.clear(); vi.useFakeTimers(); fetcher.mockReset()
  fetcher.mockImplementation(async input => response(decodeURIComponent(new URL(String(input)).pathname.split('/')[3])))
  vi.stubGlobal('fetch', fetcher)
})
afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks(); vi.unstubAllGlobals() })

describe('automatic visible image resolution', () => {
  it('enriches finish-specific prices, reuses fresh quotes on reload and explicitly refreshes without reimport', async () => {
    const variants = ['', 'foil', 'etched'].map(finish => { const row = [...syntheticRow]; row[6] = finish; return row })
    storeCollection(localStorage, syntheticCsv(variants))
    const original = localStorage.getItem(COLLECTION_KEY)
    fetcher.mockImplementation(async () => new Response(JSON.stringify(syntheticPricedResponse())))
    const first = mount()
    await advance()
    expect(first.result.current.holdings.map(row => row.priceCents)).toEqual([123, 234, 345])
    expect(fetcher).toHaveBeenCalledTimes(1)
    first.unmount()
    const second = mount()
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
    fetcher.mockImplementation(async () => new Response(JSON.stringify({ ...syntheticPricedResponse(), prices: { usd: '0.00', usd_foil: null, usd_etched: '4.00' } })))
    fireEvent.click(screen.getByRole('button', { name: 'Refresh visible estimates' }))
    await advance()
    expect(second.result.current.holdings.map(row => row.priceCents)).toEqual([0, null, 400])
    expect(fetcher).toHaveBeenCalledTimes(2)
    expect(localStorage.getItem(COLLECTION_KEY)).toBe(original)
    await advance(QUOTE_MAX_AGE_MS)
    expect(fetcher).toHaveBeenCalledTimes(2) // No background polling.
    second.unmount()
    mount()
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(3)
  })

  it.each(['legacy', 'stale', 'invalid'] as const)('refreshes %s cache only for visible printings, retaining complete images', async kind => {
    storeCollection(localStorage, syntheticCsv([syntheticRow, ...rows(12)]))
    const card = readScryfallCard(syntheticPricedResponse(), syntheticPrinting)
    const cache: Record<string, unknown> = {
      ...card,
      pricing: kind === 'legacy' ? undefined : kind === 'stale'
        ? { ...card.pricing, retrievedAt: new Date(Date.now() - QUOTE_MAX_AGE_MS).toISOString() }
        : { ...card.pricing, cents: { Nonfoil: null, Foil: null, Etched: -1 } },
    }
    localStorage.setItem(CATALOG_KEY, JSON.stringify({ [printingKey(syntheticPrinting)]: cache }))
    fetcher.mockImplementation(async () => new Response(JSON.stringify(syntheticPricedResponse())))
    const { result } = mount(1)
    expect(screen.getByRole('img')).toHaveAttribute('src')
    if (kind !== 'stale') expect(result.current.holdings[0].priceCents).toBeNull()
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(result.current.holdings[0].priceCents).toBe(345)
    expect(result.current.holdings.slice(1).every(row => row.priceCents === null)).toBe(true)
  })

  it('keeps holdings and images but marks invalid pricing unknown; retry recovers', async () => {
    storeCollection(localStorage, syntheticCsv())
    fetcher.mockResolvedValueOnce(new Response(JSON.stringify({ ...syntheticResponse(), prices: { usd_etched: 'invalid' } })))
    const { result } = mount()
    await advance()
    expect(result.current.holdings[0].priceCents).toBeNull()
    expect(screen.getByRole('img')).toHaveAttribute('src')
    expect(screen.getByText(/Pricing is invalid/)).toBeInTheDocument()
    expect(result.current.resolutionMessage).toContain('1 failed')
    fetcher.mockImplementation(async () => new Response(JSON.stringify(syntheticPricedResponse())))
    fireEvent.click(screen.getByRole('button', { name: 'Retry / resume visible images' }))
    await advance()
    expect(result.current.holdings[0].priceCents).toBe(345)
  })

  it('does not apply mismatched metadata or prices during refresh and reports the failure', async () => {
    storeCollection(localStorage, syntheticCsv())
    fetcher.mockResolvedValueOnce(new Response(JSON.stringify({ ...syntheticPricedResponse(), lang: 'en' })))
    const { result } = mount()
    await advance()
    expect(result.current.holdings[0].priceCents).toBeNull()
    expect(result.current.holdings[0].card.catalog).toBeUndefined()
    expect(screen.getByText(/different printing or language/)).toBeInTheDocument()
    expect(localStorage.getItem(CATALOG_KEY)).toBeNull()
  })

  it('retries a failed explicit refresh even when the previous cached quote is still fresh', async () => {
    storeCollection(localStorage, syntheticCsv())
    fetcher.mockImplementation(async () => new Response(JSON.stringify(syntheticPricedResponse())))
    const { result } = mount()
    await advance()
    const previous = result.current.holdings[0].card.catalog
    fetcher.mockResolvedValueOnce(new Response(JSON.stringify({ ...syntheticPricedResponse(), set: 'wrong' })))
    fireEvent.click(screen.getByRole('button', { name: 'Refresh visible estimates' }))
    await advance()
    expect(result.current.holdings[0].card.catalog).toEqual(previous)
    expect(screen.getByText(/different printing or language/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Retry / resume visible images' }))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(3)
    expect(result.current.resolutionErrors).toEqual({})
    expect(result.current.holdings[0].priceCents).toBe(345)
    expect(result.current.holdings[0].card.catalog?.pricing.retrievedAt).not.toBe(previous?.pricing.retrievedAt)
  })

  it('loads uncached imports automatically under StrictMode, deduplicates, preserves private data and reloads cached images', async () => {
    const first = mount()
    await advance()
    expect(fetcher).not.toHaveBeenCalled()
    act(() => { first.result.current.applyImport(syntheticCsv([syntheticRow, syntheticRow])) })
    const original = localStorage.getItem(COLLECTION_KEY)
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(fetcher.mock.calls[0][0]).toBe('https://api.scryfall.com/cards/tst/PCY-1/ko')
    expect(fetcher.mock.calls[0][1]).toMatchObject({ credentials: 'omit', referrerPolicy: 'no-referrer' })
    expect(fetcher.mock.calls[0][1]).not.toHaveProperty('body')
    expect(screen.getAllByRole('img')).toHaveLength(2)
    expect(screen.getAllByRole('img')[0]).toHaveAttribute('src', 'https://cards.scryfall.io/normal/front/test.jpg')
    expect(first.result.current.holdings[0]).toMatchObject({ quantity: 2, priceCents: null, moxfield: { tags: 'kept, locally', purchasePrice: '7.2500' }, card: { manaValue: 3 } })
    expect(first.result.current.holdings[1].card.catalog).toEqual(first.result.current.holdings[0].card.catalog)
    expect(localStorage.getItem(COLLECTION_KEY)).toBe(original)
    expect(localStorage.getItem(CATALOG_KEY)).not.toMatch(/purchasePrice|kept, locally/)
    const write = vi.spyOn(Storage.prototype, 'setItem')
    act(() => first.result.current.setLayout('grid'))
    first.rerender()
    await advance(10000)
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(write).not.toHaveBeenCalled()
    first.unmount()
    const second = mount()
    expect(screen.getAllByRole('img')[0]).toHaveAttribute('src', 'https://cards.scryfall.io/normal/front/test.jpg')
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(write).not.toHaveBeenCalled()
    // Applying a new snapshot also uses cached public printings immediately.
    act(() => second.result.current.applyImport(syntheticCsv()))
    expect(screen.getByRole('img')).toHaveAttribute('src', 'https://cards.scryfall.io/normal/front/test.jpg')
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
  })

  it('finishes more than eight distinct visible printings, but never scans the rest of the collection', async () => {
    storeCollection(localStorage, syntheticCsv(rows(25)))
    const { result, rerender } = mount(10)
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(10)
    expect(result.current.holdings.filter(row => row.card.catalog)).toHaveLength(10)
    expect(result.current.resolutionMessage).toContain('Checked 10 of 10')
    expect(fetcher.mock.invocationCallOrder).toHaveLength(10)
    const times = fetcher.mock.calls.map(([, options]) => options?.signal)
    expect(times.every(signal => signal && !signal.aborted)).toBe(true)
    rerender(); await advance(10000)
    expect(fetcher).toHaveBeenCalledTimes(10)
    act(() => result.current.setPage(1))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(20)
    expect(result.current.holdings.slice(20).every(row => !row.card.catalog)).toBe(true)
    act(() => result.current.setPage(0))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(20)
  })

  it('keeps the import and session images when public cache storage fails', async () => {
    storeCollection(localStorage, syntheticCsv())
    const { result } = mount()
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new DOMException('Full', 'QuotaExceededError') })
    await advance()
    expect(result.current.message).toContain('metadata could not be cached')
    expect(result.current.holdings[0].card.catalog).toBeDefined()
    expect(loadCollection(localStorage).preview?.rows).toBe(1)
    expect(screen.getByRole('img')).toHaveAttribute('src', 'https://cards.scryfall.io/normal/front/test.jpg')
  })

  it('is sequential, keeps completed images, and automatically replaces obsolete work on navigation', async () => {
    storeCollection(localStorage, syntheticCsv(rows(4)))
    let respond!: (value: Response) => void
    fetcher.mockImplementationOnce(async () => response('0')).mockImplementationOnce(() => new Promise(resolve => { respond = resolve }))
    const { result } = mount(2)
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(2)
    expect(result.current.holdings[0].card.catalog).toBeDefined()
    expect(result.current.resolving).toBe(true)
    expect(screen.queryByRole('button', { name: 'Cancel resolution' })).not.toBeInTheDocument()
    act(() => result.current.setPage(1))
    expect(fetcher.mock.calls[1][1]?.signal?.aborted).toBe(true)
    await act(async () => respond(response('1')))
    expect(result.current.holdings[1].card.catalog).toBeUndefined()
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(4)
    act(() => result.current.setPage(0))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(5)
    expect(result.current.holdings.every(row => row.card.catalog)).toBe(true)
  })

  it('has no image off switch and keeps images available across navigation, imports and temporary demo', async () => {
    storeCollection(localStorage, syntheticCsv(rows(3)))
    const { result } = mount(2)
    await advance()
    expect(screen.queryByRole('button', { name: /^(Enable|Disable) external images$/ })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Cancel resolution' })).not.toBeInTheDocument()
    expect(screen.getAllByRole('img').every(image => image.hasAttribute('src'))).toBe(true)
    act(() => result.current.setPage(1))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(3)
    expect(screen.getByRole('img')).toHaveAttribute('src')
    act(() => result.current.enableDemo())
    await advance()
    act(() => result.current.exitDemo())
    await advance()
    act(() => result.current.applyImport(syntheticCsv(rows(3))))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(3)
    expect(screen.getAllByRole('img').every(image => image.hasAttribute('src'))).toBe(true)
    expect(result.current.holdings.every(row => row.card.catalog)).toBe(true)
  })

  it('does not retry 404s on renders or page revisits; manual retry skips successes', async () => {
    storeCollection(localStorage, syntheticCsv(rows(3)))
    fetcher.mockImplementationOnce(async () => new Response('', { status: 404 }))
    const { result, rerender } = mount(2)
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(2)
    expect(result.current.holdings[0].card.manaValue).toBeNull()
    expect(screen.getByText(/No alternative printing/)).toBeInTheDocument()
    act(() => result.current.setPage(1)); await advance()
    act(() => result.current.setPage(0)); rerender(); await advance(60000)
    expect(fetcher).toHaveBeenCalledTimes(3)
    fireEvent.click(screen.getByRole('button', { name: 'Retry / resume visible images' }))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(4)
    expect(result.current.resolutionErrors).toEqual({})
    expect(result.current.holdings.every(row => row.card.catalog)).toBe(true)
  })

  it.each(['network', 'server'] as const)('loads each next page automatically after a %s failure on the previous page', async failure => {
    storeCollection(localStorage, syntheticCsv(rows(5)))
    if (failure === 'network') fetcher.mockRejectedValueOnce(new Error('synthetic network failure'))
    else fetcher.mockResolvedValueOnce(new Response('', { status: 503 }))
    const { result, rerender } = mount(2)
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(result.current.resolutionPaused).toBe(true)
    rerender(); await advance(10000)
    expect(fetcher).toHaveBeenCalledTimes(1)
    act(() => result.current.setPage(1))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(3)
    expect(result.current.holdings.slice(2, 4).every(row => row.card.catalog)).toBe(true)
    expect(result.current.holdings[4].card.catalog).toBeUndefined()
    expect(result.current.resolutionPaused).toBe(false)
    act(() => result.current.setPage(2))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(4)
    expect(result.current.holdings[4].card.catalog).toBeDefined()
    expect(result.current.holdings.slice(0, 2).every(row => !row.card.catalog)).toBe(true)
  })

  it('respects provider cooldown across pages and loads the next page once the cooldown expires', async () => {
    storeCollection(localStorage, syntheticCsv(rows(5)))
    fetcher.mockResolvedValueOnce(new Response('', { status: 429, headers: { 'Retry-After': '60' } }))
    const { result, rerender } = mount(2)
    await advance(200)
    expect(fetcher).toHaveBeenCalledTimes(1)
    act(() => result.current.setPage(1))
    await advance(500)
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(result.current.resolutionMessage).toContain('Checked 1 of 2')
    rerender(); await advance(60000)
    expect(fetcher).toHaveBeenCalledTimes(1)
    act(() => result.current.setPage(2))
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(2)
    expect(result.current.holdings[4].card.catalog).toBeDefined()
    expect(result.current.resolutionPaused).toBe(false)
  })

  it.each(['network', '429'] as const)('pauses on %s without retry loops on the same page and respects cooldown on manual resume', async failure => {
    storeCollection(localStorage, syntheticCsv(rows(3)))
    if (failure === 'network') fetcher.mockRejectedValueOnce(new Error('synthetic network failure'))
    else fetcher.mockResolvedValueOnce(new Response('', { status: 429, headers: { 'Retry-After': '60' } }))
    const { result, rerender } = mount(1)
    await advance(200)
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(result.current.resolutionPaused).toBe(true)
    rerender(); await advance(500)
    expect(fetcher).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByRole('button', { name: 'Retry / resume visible images' }))
    await advance(500)
    if (failure === '429') {
      expect(fetcher).toHaveBeenCalledTimes(1)
      expect(result.current.resolutionPaused).toBe(true)
      await advance(60000)
      expect(fetcher).toHaveBeenCalledTimes(1)
      fireEvent.click(screen.getByRole('button', { name: 'Retry / resume visible images' }))
      await advance()
    }
    expect(fetcher).toHaveBeenCalledTimes(2)
    expect(result.current.holdings[0].card.catalog).toBeDefined()
  })

  it.each(['page', 'import', 'demo', 'clear', 'unmount'] as const)('ignores stale async results after %s without clearing a newer controller', async change => {
    storeCollection(localStorage, syntheticCsv(rows(3)))
    const pending: ((value: Response) => void)[] = []
    fetcher.mockImplementation(() => new Promise(resolve => { pending.push(resolve) }))
    const page = mount(1)
    await advance()
    const oldSignal = fetcher.mock.calls[0][1]?.signal
    if (change === 'unmount') page.unmount()
    else act(() => {
      if (change === 'page') page.result.current.setPage(1)
      if (change === 'import') page.result.current.applyImport(syntheticCsv([rows(3)[2]]))
      if (change === 'demo') page.result.current.enableDemo()
      if (change === 'clear') page.result.current.clearCollection()
    })
    await advance()
    expect(oldSignal?.aborted).toBe(true)
    await act(async () => pending[0](response('0')))
    expect(localStorage.getItem(CATALOG_KEY)).toBeNull()
    if (change === 'page' || change === 'import') {
      expect(fetcher).toHaveBeenCalledTimes(2)
      expect(page.result.current.resolving).toBe(true)
      act(() => page.result.current.clearCollection())
      expect(fetcher.mock.calls[1][1]?.signal?.aborted).toBe(true)
      await act(async () => pending[1](response(change === 'page' ? '1' : '2')))
      expect(localStorage.getItem(CATALOG_KEY)).toBeNull()
      expect(page.result.current.resolutionErrors).toEqual({})
    } else {
      expect(fetcher).toHaveBeenCalledTimes(1)
    }
    await advance(60000)
    expect(fetcher).toHaveBeenCalledTimes(change === 'page' || change === 'import' ? 2 : 1)
  })

  it('never requests provider data for empty/demo, and demo leaves the stored import intact', async () => {
    const { result } = mount()
    await advance()
    act(() => result.current.enableDemo())
    await advance()
    expect(fetcher).not.toHaveBeenCalled()
    act(() => result.current.applyImport(syntheticCsv()))
    await advance()
    const original = localStorage.getItem(COLLECTION_KEY)
    act(() => result.current.enableDemo())
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
    expect(localStorage.getItem(COLLECTION_KEY)).toBe(original)
    act(() => result.current.exitDemo())
    await advance()
    expect(fetcher).toHaveBeenCalledTimes(1)
  })
})
